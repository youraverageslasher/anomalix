/*
 * Anomalix: GISTEMP fallback snapshot (build:gistemp)
 * The app reads GLB.Ts+dSST.csv and ZonAnn.Ts+dSST.csv live from NASA GISS. When that request fails in production,
 * it falls back to the copies in data/gistemp/, bundled through src/lib/data/gistempSnapshot.ts.
 *   npm run build:gistemp            regenerate the module from the files already in data/gistemp/
 *   npm run build:gistemp -- --fetch download fresh copies first, record the fetch date, then regenerate
 * The files are stored byte for byte as NASA serves them; the SHA-256 of each is written next to it.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const dir = path.join(root, "data/gistemp");
const metaPath = path.join(dir, "snapshot.json");
const meta = JSON.parse(readFileSync(metaPath, "utf8"));
const names = ["GLB.Ts+dSST.csv", "ZonAnn.Ts+dSST.csv"];

if (process.argv.includes("--fetch")) {
  let lastModified = null;
  for (const name of names) {
    const res = await fetch(meta.files[name], { headers: { "User-Agent": "Anomalix/1.0 (NASA Space Apps 2026)" } });
    if (!res.ok) throw new Error(`${name}: NASA GISS answered ${res.status}`);
    writeFileSync(path.join(dir, name), await res.text());
    lastModified = res.headers.get("last-modified") ?? lastModified;
  }
  meta.fetchedAt = new Date().toISOString().replace(/\.\d{3}Z$/, "Z");
  meta.lastModified = lastModified ? new Date(lastModified).toISOString().replace(/\.\d{3}Z$/, "Z") : null;
  writeFileSync(metaPath, JSON.stringify(meta, null, 2) + "\n");
}

const sha = (s) => createHash("sha256").update(s, "utf8").digest("hex");
const glb = readFileSync(path.join(dir, names[0]), "utf8");
const zonal = readFileSync(path.join(dir, names[1]), "utf8");
const out = `/* Generated by scripts/build-gistemp-snapshot.mjs from data/gistemp/. Do not edit by hand. */
export const GISTEMP_SNAPSHOT = {
  fetchedAt: ${JSON.stringify(meta.fetchedAt)},
  lastModified: ${JSON.stringify(meta.lastModified)},
  glb: { sha256: ${JSON.stringify(sha(glb))}, csv: ${JSON.stringify(glb)} },
  zonal: { sha256: ${JSON.stringify(sha(zonal))}, csv: ${JSON.stringify(zonal)} },
} as const;
`;
writeFileSync(path.join(root, "src/lib/data/gistempSnapshot.ts"), out);
console.log(`gistempSnapshot.ts written: fetched ${meta.fetchedAt}, GLB ${sha(glb).slice(0, 12)}, ZonAnn ${sha(zonal).slice(0, 12)}`);
